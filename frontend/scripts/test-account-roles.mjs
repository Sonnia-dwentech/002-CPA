import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import { LocalAccountStore } from '../lib/local-account-store.ts';
const store = new LocalAccountStore(':memory:');
const password = randomBytes(24).toString('hex');
const external = await store.authenticate('signup', {email:'external@example.test',name:'External',password,role:'admin'});
assert.equal(external.user.role,'external');
assert.throws(() => store.adminUsers(external.token),e=>e.status===403);
const setup = store.issueAdminSetup();
assert.equal(store.db.prepare('SELECT digest FROM admin_setup WHERE digest=?').get(setup),undefined);
const admin = await store.authenticate('signup',{email:'admin@example.test',name:'Admin',password,adminSetup:setup});
assert.equal(admin.user.role,'admin');
assert.equal(store.user(admin.token).role,'admin');
assert.equal(store.adminUsers(admin.token).length,2);
assert.ok(!('password_hash' in store.adminUsers(admin.token)[0]));
await assert.rejects(store.authenticate('login',{email:'external@example.test',password,adminSetup:setup}),e=>e.status===403);
assert.throws(()=>store.setAccountEnabled(external.token,admin.user.id,false),e=>e.status===403);
store.addIdea(admin.user.id,{title:'Admin private'});
assert.equal(store.ideas(external.user.id).length,0);
store.setAccountEnabled(admin.token,external.user.id,false);
assert.throws(()=>store.user(external.token),e=>e.status===401);
await assert.rejects(store.authenticate('login',{email:'external@example.test',password}),e=>e.status===401);
store.setAccountEnabled(admin.token,external.user.id,true);
const restored = await store.authenticate('login',{email:'external@example.test',password});
assert.equal(restored.user.role,'external');
assert.throws(()=>store.setAccountEnabled(admin.token,admin.user.id,false),e=>e.status===403);
assert.equal(store.db.prepare('SELECT count(*) AS n FROM account_audit').get().n,3);
const upgrade = store.issueAdminSetup();
const promoted = await store.authenticate('login',{email:'external@example.test',password,adminSetup:upgrade});
assert.equal(promoted.user.role,'admin');
assert.throws(()=>store.user(restored.token),e=>e.status===401);
store.db.close();
console.log('PASS: server-owned roles, one-use hashed setup, signup and existing-account upgrade, revoked old sessions, admin-only metadata, external denial, suspension/reactivation, audit and private ideas.');
