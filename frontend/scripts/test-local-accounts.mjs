import assert from 'node:assert/strict';
import { mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { randomBytes } from 'node:crypto';
import { LocalAccountStore } from '../lib/local-account-store.ts';

const directory = mkdtempSync(path.join(tmpdir(), 'cpa-account-check-'));
const filename = path.join(directory, 'test.sqlite');
let store = new LocalAccountStore(filename);
const password = randomBytes(24).toString('hex');
const a = await store.authenticate('signup', { email: 'first@example.test', name: 'First test user', password });
const b = await store.authenticate('signup', { email: 'second@example.test', name: 'Second test user', password });
assert.notEqual(a.token, b.token);
assert.equal(store.user(a.token).id, a.user.id);
await assert.rejects(store.authenticate('login', { email: 'first@example.test', password: 'incorrect password here' }), e => e.status === 401);
await assert.rejects(store.authenticate('login', { email: 'unknown@example.test', password }), e => e.status === 401);
await assert.rejects(store.authenticate('signup', { email: 'FIRST@example.test', name: 'Duplicate', password }), e => e.status === 409);
await assert.rejects(store.authenticate('signup', { email: 'weak@example.test', name: 'Weak', password: 'short' }), e => e.status === 422);
store.addIdea(a.user.id, { title: 'Private test idea', description: '<script>text only</script>' });
assert.equal(store.ideas(a.user.id).length, 1);
assert.equal(store.ideas(b.user.id).length, 0);
const stored = store.db.prepare('SELECT * FROM accounts WHERE id=?').get(a.user.id);
assert.notEqual(stored.password_hash, password);
assert.equal(store.db.prepare('SELECT * FROM sessions WHERE digest=?').get(a.token), undefined);
assert.throws(() => store.user('invalid'), e => e.status === 401);
assert.throws(() => store.user(a.token, Date.now() + 31 * 60_000), e => e.status === 401);
store.logout(a.token);
assert.throws(() => store.user(a.token), e => e.status === 401);
store.db.close();
store = new LocalAccountStore(filename);
const again = await store.authenticate('login', { email: ' FIRST@example.test ', password });
assert.equal(store.ideas(again.user.id).length, 1);
for (let i=0;i<3;i++) store.limit('test-limiter', 3);
assert.throws(() => store.limit('test-limiter', 3), e => e.status === 429);
store.db.close();
console.log('PASS: signup, password verification, duplicate/weak rejection, account isolation, hashed storage, expiry, logout, persisted login/ideas and throttling. Isolated test database retained.');
